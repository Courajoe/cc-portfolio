/**
 * Generates lib/land-mask.ts: a 1°×1° land/ocean bitmask of the Earth that
 * the dotted globe (components/EarthScene.tsx) uses to decide where to put
 * land dots.
 *
 * Source: Natural Earth 1:50m land polygons (public domain), via the
 * `world-atlas` package. The output is 360×180 bits (8,100 bytes), stored as
 * base64 (~11 KB), so the browser never downloads map data or textures.
 *
 * Run it again only if you want a different resolution:
 *   pnpm gen:land-mask
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topology = require("world-atlas/land-50m.json");
const land = feature(topology, topology.objects.land);

const WIDTH = 360; // columns: longitude -180 → 180
const HEIGHT = 180; // rows: latitude 90 → -90 (north first)

/**
 * Make a ring's longitudes continuous: whenever an edge jumps by more than
 * 180° (crossing the antimeridian), shift the rest of the ring by ±360°.
 * A ring that circles a pole (Antarctica) then doesn't close on itself, so
 * close it through that pole.
 */
function unwrapRing(ring) {
  const out = [ring[0].slice()];
  let offset = 0;
  for (let i = 1; i < ring.length; i++) {
    const [x, y] = ring[i];
    const prev = ring[i - 1][0];
    if (x - prev > 180) offset -= 360;
    else if (prev - x > 180) offset += 360;
    out.push([x + offset, y]);
  }
  const first = out[0];
  const last = out[out.length - 1];
  if (Math.abs(last[0] - first[0]) > 180) {
    const poleLat = out.reduce((sum, [, y]) => sum + y, 0) < 0 ? -90 : 90;
    out.push([last[0], poleLat], [first[0], poleLat], first.slice());
  }
  return out;
}

// Flatten to polygons of [outerRing, ...holes], each with a bounding box so
// most point tests are rejected cheaply. A planar (lon/lat) test is plenty
// accurate at 1° resolution, and far faster than a spherical one.
const geometries = land.type === "FeatureCollection" ? land.features.map((f) => f.geometry) : [land.geometry];
const polygons = geometries
  .flatMap((g) => (g.type === "MultiPolygon" ? g.coordinates : [g.coordinates]))
  .map((rawRings) => {
    const rings = rawRings.map(unwrapRing);
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (const [x, y] of rings[0]) {
      minX = Math.min(minX, x); maxX = Math.max(maxX, x);
      minY = Math.min(minY, y); maxY = Math.max(maxY, y);
    }
    return { rings, minX, minY, maxX, maxY };
  });

/** Even-odd ray casting against one ring. */
function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function isLand(lon, lat) {
  return polygons.some((p) =>
    // Unwrapped rings can extend past ±180°, so also try the point shifted by 360°.
    [lon, lon + 360, lon - 360].some(
      (x) =>
        x >= p.minX && x <= p.maxX && lat >= p.minY && lat <= p.maxY &&
        inRing(x, lat, p.rings[0]) &&
        !p.rings.slice(1).some((hole) => inRing(x, lat, hole)),
    ),
  );
}

const bytes = new Uint8Array((WIDTH * HEIGHT) / 8);
let landCells = 0;

for (let row = 0; row < HEIGHT; row++) {
  const lat = 90 - row - 0.5; // cell centre
  for (let col = 0; col < WIDTH; col++) {
    const lon = -180 + col + 0.5;
    if (isLand(lon, lat)) {
      const bit = row * WIDTH + col;
      bytes[bit >> 3] |= 1 << (bit & 7);
      landCells++;
    }
  }
}

const out = `// AUTO-GENERATED by scripts/generate-land-mask.mjs. Do not edit by hand.
// 1°×1° land bitmask of the Earth (Natural Earth 1:50m, public domain).
// Bit (row * ${WIDTH} + col) is 1 where there is land; row 0 = 90°N, col 0 = 180°W.

export const LAND_MASK_WIDTH = ${WIDTH};
export const LAND_MASK_HEIGHT = ${HEIGHT};
export const LAND_MASK_BASE64 =
  "${Buffer.from(bytes).toString("base64")}";
`;

const target = path.join(process.cwd(), "lib", "land-mask.ts");
fs.writeFileSync(target, out);
console.log(
  `Wrote ${path.relative(process.cwd(), target)}: ${landCells} land cells ` +
    `(${((landCells / (WIDTH * HEIGHT)) * 100).toFixed(1)}%).`,
);
